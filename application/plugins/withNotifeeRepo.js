// Expo config plugin: tell Gradle where to find notifee's Android artifact.
//
// @notifee/react-native does NOT publish app.notifee:core to Maven Central,
// jitpack or Google — it ships the artifact inside node_modules, at
// node_modules/@notifee/react-native/android/libs, and expects the app's
// build.gradle to add that folder as a local maven repository. Autolinking wires
// the MODULE up but says nothing about where its dependency comes from, so
// without this the build gets all the way to dependency resolution and dies:
//
//   Could not find any matches for app.notifee:core:+
//     Required by: project :app > project :notifee_react-native
//
// which reads like a network problem and is not one — the file is on disk the
// whole time.
//
// A plugin rather than a hand-edit of android/build.gradle because android/ is
// gitignored (.gitignore) and regenerated by prebuild, so an edit there survives
// exactly until the next `expo prebuild` and then the same failure comes back
// with nothing in version control explaining it.
const { withProjectBuildGradle } = require('@expo/config-plugins');

// $rootDir is android/, so ../node_modules reaches the project's own copy. Kept
// relative so it works on any machine and inside EAS, where absolute paths differ.
const REPO = "maven { url \"$rootDir/../node_modules/@notifee/react-native/android/libs\" }";

module.exports = function withNotifeeRepo(config) {
  return withProjectBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') return cfg;
    if (cfg.modResults.contents.includes('@notifee/react-native/android/libs')) return cfg;

    // Into allprojects.repositories, beside google() and mavenCentral(), which is
    // where every subproject (including :notifee_react-native) looks.
    cfg.modResults.contents = cfg.modResults.contents.replace(
      /allprojects\s*\{\s*repositories\s*\{/,
      (m) => `${m}\n    ${REPO}`,
    );
    return cfg;
  });
};
