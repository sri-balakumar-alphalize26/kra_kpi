// Expo config plugin: an Android home-screen widget showing the running task and
// a live ticking timer — and, dragged taller, the day's Presence / Productive
// clocks and the current break, plus a Pause / Resume button.
//
// WHY A PLUGIN AND NOT AN android/ FOLDER: this project is pure CNG — there is no
// android/ directory (it is gitignored, .gitignore:36-38) and the native project
// is regenerated from app.json on every EAS build. Files dropped into android/
// would be deleted before they were ever compiled. Everything the widget needs
// therefore has to be WRITTEN at prebuild time, which is what withDangerousMod
// below does.
//
// WHY A Chronometer AND NOT A TICKING UPDATE: a widget process cannot call into
// the React Native bundle, and AppWidgetProvider updates are rate-limited to once
// every 30 minutes by the OS — so a per-second timer driven from JS is simply not
// possible. Android's Chronometer view counts on its own once given a base
// timestamp, so the widget is handed "this task started at T" ONCE and then ticks
// for free, with no broadcasts, no wakelocks and no battery cost. The day clocks
// in the details block work the same way, each from its own anchor.
//
// WHERE THE DATA COMES FROM: a small JSON file the app writes into its own
// filesDir (utils/taskWidget.js, via expo-file-system's documentDirectory, which
// on Android IS /data/user/0/<pkg>/files — the same directory Kotlin's
// context.filesDir points at). Its shape is utils/taskWidgetState.js, which is
// unit-tested. Deliberately NOT AsyncStorage: that is SQLite on Android, and a
// widget cannot open it. Deliberately not a native module either — a file needs
// no bridge, no autolinking, and no new dependency.
//
// HOW IT STAYS FRESH: modules/expo-task-widget-bridge broadcasts APPWIDGET_UPDATE
// as soon as the state file changes, so a task switch shows within seconds.
// Without it the only refresh is android:updatePeriodMillis, whose floor is 30
// MINUTES — which is what the widget used to be stuck with, and why this file
// once documented a lag it no longer has.
//
// HOW IT KNOWS IT IS STALE: the file carries `published_at`, re-stamped by the
// app every few minutes while it is open. With the app closed the stamp stops
// moving, and at the next OS refresh the widget says "Open the app to refresh"
// rather than presenting an hour-old task as the current one.
//
// WHY THE BUTTON OPENS THE APP: a widget cannot call the server — it has no
// session, and the auth lives in the JS. So Pause / Resume are deep links
// (krakpi://widget/home?action=…) that land on Home, which already owns the pause
// dialog and the resume call. One tap fewer than opening the app and finding the
// card; no second copy of any flow.
//
// Applied at prebuild/EAS-build time; needs a rebuild to take effect and CANNOT
// work in Expo Go.

const {
  withAndroidManifest,
  withDangerousMod,
  AndroidConfig,
} = require('@expo/config-plugins');
const path = require('path');
const { previewVector, write, writeSharedWidgetRes } = require('./widgetShared');

const WIDGET_CLASS = 'TaskWidgetProvider';
// Must match WIDGET_FILE in utils/taskWidget.js. Lives in the app's filesDir,
// which both sides can reach.
const STATE_FILE = 'task_widget.json';
// Tapping the widget opens the board rather than dumping the user on Home. Read
// by App.js through utils/widgetLink.js; the scheme is declared in app.json.
const DEEP_LINK = 'krakpi://widget/actionboard';
// The button's link. App.js hands the action to Home (screens/HomeScreen.js).
const HOME_LINK = 'krakpi://widget/home';

// ---------------------------------------------------------------- Kotlin ----
const providerKt = (pkg) => `package ${pkg}

// GENERATED by plugins/withTaskWidget.js — do not edit by hand, this file is
// rewritten on every prebuild.
//
// Reads the JSON the app last wrote into filesDir (shape: utils/taskWidgetState.js)
// and renders it. Every counter is a Chronometer seeded with a base in
// SystemClock.elapsedRealtime terms, so it counts up by itself without this
// provider being woken again.

import android.app.PendingIntent
import android.appwidget.AppWidgetManager
import android.appwidget.AppWidgetProvider
import android.content.Context
import android.content.Intent
import android.net.Uri
import android.os.Bundle
import android.os.SystemClock
import android.view.View
import android.widget.RemoteViews
import org.json.JSONObject
import java.io.File
import kotlin.math.max

class ${WIDGET_CLASS} : AppWidgetProvider() {

    companion object {
        // Older than this and the app has not touched the file for a while: it is
        // closed, and whatever is on screen is history. utils/taskWidget.js
        // re-stamps an unchanged file every 5 min while the app is open, so a
        // foreground app never trips this; the OS refresh (30 min) is when a
        // closed one does.
        private const val STALE_MS = 20L * 60L * 1000L
        private const val STALE_TEXT = "Open the app to refresh"
        // The details block needs a second row of cells. One cell is 70-120dp
        // depending on the launcher; two is 150dp and up.
        private const val DETAILS_MIN_DP = 150
    }

    override fun onUpdate(
        context: Context,
        appWidgetManager: AppWidgetManager,
        appWidgetIds: IntArray
    ) {
        for (id in appWidgetIds) render(context, appWidgetManager, id)
    }

    /** Resizing does not go through onUpdate: without this the details block
     *  would stay hidden after the widget is dragged taller. */
    override fun onAppWidgetOptionsChanged(
        context: Context,
        appWidgetManager: AppWidgetManager,
        appWidgetId: Int,
        newOptions: Bundle?
    ) {
        super.onAppWidgetOptionsChanged(context, appWidgetManager, appWidgetId, newOptions)
        render(context, appWidgetManager, appWidgetId)
    }

    /** Never throws: a widget that crashes is removed from the home screen by
     *  the launcher, so a malformed or half-written file must degrade to the
     *  empty state instead. */
    private fun readState(context: Context): JSONObject {
        return try {
            val f = File(context.filesDir, "${STATE_FILE}")
            if (!f.exists()) JSONObject() else JSONObject(f.readText())
        } catch (e: Exception) {
            JSONObject()
        }
    }

    /** Room for the details block, from the height the launcher gives us.
     *  0 = not told yet: compact, so a freshly placed strip is never clipped. */
    private fun detailsFit(mgr: AppWidgetManager, widgetId: Int): Boolean {
        val h = try {
            mgr.getAppWidgetOptions(widgetId)
                .getInt(AppWidgetManager.OPTION_APPWIDGET_MIN_HEIGHT, 0)
        } catch (e: Exception) {
            0
        }
        return h >= DETAILS_MIN_DP
    }

    /** A tap that opens the app on one of its own links (ACTION_VIEW on the app's
     *  scheme; setPackage keeps it inside this app). App.js routes the rest. */
    private fun pendingLink(context: Context, requestCode: Int, url: String): PendingIntent {
        val launch = Intent(Intent.ACTION_VIEW, Uri.parse(url)).apply {
            setPackage(context.packageName)
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TOP)
        }
        val flags = PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE
        return PendingIntent.getActivity(context, requestCode, launch, flags)
    }

    /** The elapsedRealtime base that makes a Chronometer read the given seconds now. */
    private fun baseFor(seconds: Long): Long = SystemClock.elapsedRealtime() - seconds * 1000L

    private fun render(context: Context, mgr: AppWidgetManager, widgetId: Int) {
        val state = readState(context)
        val views = RemoteViews(context.packageName, R.layout.task_widget)
        val now = System.currentTimeMillis()

        val publishedAt = state.optLong("published_at", 0L)
        val stale = publishedAt > 0L && now - publishedAt > STALE_MS

        val taskName = state.optString("task_name", "")
        val running = state.optBoolean("running", false)
        val count = state.optInt("task_count", 0)
        // Device-clock ms at which the current timer started (the app has already
        // corrected it for clock skew), plus any time already banked on the task.
        val startedAtMs = state.optLong("started_at_ms", 0L)
        val baseSeconds = state.optLong("base_seconds", 0L)
        val isRunning = running && taskName.isNotEmpty() && startedAtMs > 0L

        if (isRunning) {
            views.setTextViewText(R.id.widget_task, taskName)
            views.setViewVisibility(R.id.widget_timer, View.VISIBLE)
            views.setViewVisibility(R.id.widget_idle, View.GONE)
            // The dot says "live"; a stale card has no business claiming that.
            views.setViewVisibility(R.id.widget_dot, if (stale) View.GONE else View.VISIBLE)

            // Chronometer counts from a base expressed in elapsedRealtime, not in
            // wall-clock. Convert: how long ago did it start, in elapsedRealtime
            // terms, minus the seconds already banked so the display shows the
            // task's TOTAL time rather than only this sitting.
            val elapsedSinceStart = max(0L, now - startedAtMs)
            val base = SystemClock.elapsedRealtime() - elapsedSinceStart - (baseSeconds * 1000L)
            views.setChronometer(R.id.widget_timer, base, null, true)
            views.setTextColor(
                R.id.widget_timer,
                context.getColor(if (stale) R.color.widget_muted else R.color.widget_accent)
            )

            views.setTextViewText(
                R.id.widget_sub,
                when {
                    stale -> STALE_TEXT
                    count > 1 -> "Multi-tasking " + count + " tasks"
                    else -> "Working"
                }
            )
        } else {
            views.setViewVisibility(R.id.widget_timer, View.GONE)
            views.setViewVisibility(R.id.widget_idle, View.VISIBLE)
            views.setViewVisibility(R.id.widget_dot, View.GONE)
            views.setTextViewText(R.id.widget_task, "No task running")
            views.setTextViewText(
                R.id.widget_sub,
                when {
                    stale -> STALE_TEXT
                    state.optBoolean("workday_open", false) -> "Workday open"
                    else -> "Workday not started"
                }
            )
        }

        // The button: Pause while a task runs, Resume while a break was taken from
        // one. Hidden when there is nothing to act on — and when stale, because a
        // Pause aimed at a task that may have ended an hour ago is a wrong action.
        val kpiId = state.optLong("kpi_id", 0L)
        val resumeId = state.optLong("resume_kpi_id", 0L)
        val action: String? = when {
            stale -> null
            isRunning && kpiId > 0L -> "pause"
            !isRunning && resumeId > 0L -> "resume"
            else -> null
        }
        if (action == null) {
            views.setViewVisibility(R.id.widget_action, View.GONE)
        } else {
            val target = if (action == "pause") kpiId else resumeId
            views.setViewVisibility(R.id.widget_action, View.VISIBLE)
            views.setTextViewText(R.id.widget_action, if (action == "pause") "Pause" else "Resume")
            views.setOnClickPendingIntent(
                R.id.widget_action,
                pendingLink(context, 2, "${HOME_LINK}?action=" + action + "&kpi=" + target)
            )
        }

        // The details block: only once the widget has been dragged tall enough,
        // and only when there is a day to describe.
        val loginMs = state.optLong("login_raw_ms", 0L)
        if (!detailsFit(mgr, widgetId) || loginMs <= 0L) {
            views.setViewVisibility(R.id.widget_details, View.GONE)
        } else {
            views.setViewVisibility(R.id.widget_details, View.VISIBLE)

            // Presence: the clock since login minus the pauses — the closed ones
            // (paused_base_s) and the open one (paused_since_ms). Frozen, not
            // hidden, while the workday is paused. Same maths as presenceLive in
            // utils/liveTime.js; utils/__tests__/taskWidgetState.test.js holds
            // the two together.
            val isPaused = state.optBoolean("is_paused", false)
            val pausedSince = state.optLong("paused_since_ms", 0L)
            val openPause = if (pausedSince > 0L) max(0L, (now - pausedSince) / 1000L) else 0L
            val presence = max(
                0L,
                (now - loginMs) / 1000L - state.optLong("paused_base_s", 0L) - openPause
            )
            views.setChronometer(R.id.widget_presence, baseFor(presence), null, !isPaused)

            // Productive: finished-log base plus EVERY running timer, so it ticks
            // at the right rate while multitasking (productiveLive does the same).
            var productive = state.optLong("productive_base_s", 0L)
            var ticking = false
            val starts = state.optJSONArray("running_started_at_ms")
            if (starts != null) {
                for (i in 0 until starts.length()) {
                    val t = starts.optLong(i, 0L)
                    if (t > 0L) {
                        productive += max(0L, (now - t) / 1000L)
                        ticking = true
                    }
                }
            }
            views.setChronometer(R.id.widget_productive, baseFor(productive), null, ticking)

            // Away: a declared break / lunch / meeting, with its own clock.
            val awayLabel = state.optString("away_label", "")
            val awayAt = state.optLong("away_started_at_ms", 0L)
            if (awayLabel.isNotEmpty() && awayAt > 0L) {
                views.setViewVisibility(R.id.widget_away_row, View.VISIBLE)
                views.setTextViewText(R.id.widget_away_label, awayLabel)
                views.setChronometer(
                    R.id.widget_away_timer,
                    baseFor(max(0L, (now - awayAt) / 1000L)),
                    null,
                    true
                )
            } else {
                views.setViewVisibility(R.id.widget_away_row, View.GONE)
            }
        }

        // Tapping the card opens the BOARD, not just the app. A widget that shows
        // a task and then drops you on Home to navigate yourself is the version
        // people stop tapping.
        views.setOnClickPendingIntent(R.id.widget_root, pendingLink(context, 0, "${DEEP_LINK}"))

        mgr.updateAppWidget(widgetId, views)
    }
}
`;

