function write(file, contents) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents, 'utf8');
}

// --------------------------------------------------------------- plugin ----
module.exports = function withTaskWidget(config) {
  // 1. Emit the Kotlin provider + the res/ files into the generated project.
  config = withDangerousMod(config, [
    'android',
    (cfg) => {
      const pkg = AndroidConfig.Package.getPackage(cfg);
      if (!pkg) {
        throw new Error('withTaskWidget: android.package is not set in app.json');
      }
      const root = cfg.modRequest.platformProjectRoot; // .../android
      const main = path.join(root, 'app', 'src', 'main');

      write(
        path.join(main, 'java', ...pkg.split('.'), `${WIDGET_CLASS}.kt`),
        providerKt(pkg),
      );
      write(path.join(main, 'res', 'xml', 'task_widget_info.xml'), widgetInfoXml);
      write(path.join(main, 'res', 'layout', 'task_widget.xml'), widgetLayoutXml);
      write(path.join(main, 'res', 'drawable', 'task_widget_bg.xml'), widgetBgXml);
      write(path.join(main, 'res', 'values', 'task_widget_strings.xml'), widgetStringsXml);

      return cfg;
    },
  ]);

  // 2. Register the receiver. Separate mod so it runs against the parsed
  //    manifest rather than by patching XML text.
  config = withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.receiver = app.receiver || [];

    const name = `.${WIDGET_CLASS}`;
    // Idempotent: prebuild can run more than once against the same manifest, and
    // a duplicated receiver is a manifest-merger failure.
    if (!app.receiver.some((r) => r.$ && r.$['android:name'] === name)) {
      app.receiver.push({
        $: {
          'android:name': name,
          // Not exported: nothing outside the app should be able to poke it. The
          // OS delivers APPWIDGET_UPDATE regardless of this flag.
          'android:exported': 'false',
        },
        'intent-filter': [
          { action: [{ $: { 'android:name': 'android.appwidget.action.APPWIDGET_UPDATE' } }] },
        ],
        'meta-data': [
          {
            $: {
              'android:name': 'android.appwidget.provider',
              'android:resource': '@xml/task_widget_info',
            },
          },
        ],
      });
    }
    return cfg;
  });

  return config;
};
