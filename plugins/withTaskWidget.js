// Expo config plugin: an Android home-screen widget showing the running task and
// a live ticking timer.
//
// WHY A PLUGIN AND NOT AN android/ FOLDER: this project is pure CNG — there is no
// android/ directory (it is gitignored, .gitignore:36-38) and the native project
// is regenerated from app.json on every EAS build. Files dropped into android/
// would be deleted before they were ever compiled. Everything the widget needs
// therefore has to be WRITTEN at prebuild time, which is what withDangerousMod
// below does.
//
// WHY A Chronometer AND NOT A TICKING UPDATE: a widget process cannot call into
// the React Native bundle, and AppWidgetProvider updates are rate-limited to once
// every 30 minutes by the OS — so a per-second timer driven from JS is simply not
// possible. Android's Chronometer view counts on its own once given a base
// timestamp, so the widget is handed "this task started at T" ONCE and then ticks
// for free, with no broadcasts, no wakelocks and no battery cost.
//
// WHERE THE DATA COMES FROM: a small JSON file the app writes into its own
// filesDir (utils/taskWidget.js, via expo-file-system's documentDirectory, which
// on Android IS /data/user/0/<pkg>/files — the same directory Kotlin's
// context.filesDir points at). Deliberately NOT AsyncStorage: that is SQLite on
// Android, and a widget cannot open it. Deliberately not a native module either
// — a file needs no bridge, no autolinking, and no new dependency.
//
// HOW IT STAYS FRESH: modules/expo-task-widget-bridge broadcasts APPWIDGET_UPDATE
// as soon as the state file changes, so a task switch shows within seconds.
// Without it the only refresh is android:updatePeriodMillis, whose floor is 30
// MINUTES — which is what the widget used to be stuck with, and why this file
// once documented a lag it no longer has.
//
// Applied at prebuild/EAS-build time; needs a rebuild to take effect and CANNOT
// work in Expo Go.

const {
  withAndroidManifest,
  withDangerousMod,
  AndroidConfig,
} = require('@expo/config-plugins');
const path = require('path');
const { previewVector, write, writeSharedWidgetRes } = require('./widgetShared');

const WIDGET_CLASS = 'TaskWidgetProvider';
// Must match WIDGET_FILE in utils/taskWidget.js. Lives in the app's filesDir,
// which both sides can reach.
const STATE_FILE = 'task_widget.json';
// Tapping the widget opens the board rather than dumping the user on Home. Read
// by App.js through Linking; the scheme is declared in app.json.
const DEEP_LINK = 'krakpi://widget/actionboard';

// ---------------------------------------------------------------- Kotlin ----
const providerKt = (pkg) => `package ${pkg}

// GENERATED by plugins/withTaskWidget.js — do not edit by hand, this file is
// rewritten on every prebuild.
//
// Reads the JSON the app last wrote into filesDir and renders it. The elapsed
// time is a Chronometer seeded with a base in SystemClock.elapsedRealtime terms,
// so it counts up by itself without this provider being woken again.

import android.app.PendingIntent
import android.appwidget.AppWidgetManager
import android.appwidget.AppWidgetProvider
import android.content.Context
import android.content.Intent
import android.net.Uri
import android.os.SystemClock
import android.view.View
import android.widget.RemoteViews
import org.json.JSONObject
import java.io.File

class ${WIDGET_CLASS} : AppWidgetProvider() {

    override fun onUpdate(
        context: Context,
        appWidgetManager: AppWidgetManager,
        appWidgetIds: IntArray
    ) {
        for (id in appWidgetIds) {
            render(context, appWidgetManager, id)
        }
    }

    /** Never throws: a widget that crashes is removed from the home screen by
     *  the launcher, so a malformed or half-written file must degrade to the
     *  empty state instead. */
    private fun readState(context: Context): JSONObject {
        return try {
            val f = File(context.filesDir, "${STATE_FILE}")
            if (!f.exists()) JSONObject() else JSONObject(f.readText())
        } catch (e: Exception) {
            JSONObject()
        }
    }

    private fun render(context: Context, mgr: AppWidgetManager, widgetId: Int) {
        val state = readState(context)
        val views = RemoteViews(context.packageName, R.layout.task_widget)

        val taskName = state.optString("task_name", "")
        val running = state.optBoolean("running", false)
        val count = state.optInt("task_count", 0)
        // Wall-clock ms at which the current timer started, plus any time already
        // banked on the task before this run.
        val startedAtMs = state.optLong("started_at_ms", 0L)
        val baseSeconds = state.optLong("base_seconds", 0L)

        if (running && taskName.isNotEmpty() && startedAtMs > 0L) {
            views.setTextViewText(R.id.widget_task, taskName)
            views.setViewVisibility(R.id.widget_timer, View.VISIBLE)
            views.setViewVisibility(R.id.widget_idle, View.GONE)
            views.setViewVisibility(R.id.widget_dot, View.VISIBLE)

            // Chronometer counts from a base expressed in elapsedRealtime, not in
            // wall-clock. Convert: how long ago did it start, in elapsedRealtime
            // terms, minus the seconds already banked so the display shows the
            // task's TOTAL time rather than only this sitting.
            val elapsedSinceStart = System.currentTimeMillis() - startedAtMs
            val base = SystemClock.elapsedRealtime() - elapsedSinceStart - (baseSeconds * 1000L)
            views.setChronometer(R.id.widget_timer, base, null, true)

            views.setTextViewText(
                R.id.widget_sub,
                if (count > 1) "Multi-tasking " + count + " tasks" else "Working"
            )
        } else {
            views.setViewVisibility(R.id.widget_timer, View.GONE)
            views.setViewVisibility(R.id.widget_idle, View.VISIBLE)
            views.setViewVisibility(R.id.widget_dot, View.GONE)
            views.setTextViewText(R.id.widget_task, "No task running")
            views.setTextViewText(
                R.id.widget_sub,
                if (state.optBoolean("workday_open", false)) "Workday open" else "Workday not started"
            )
        }

        // Tapping opens the BOARD, not just the app. A widget that shows a task
        // and then drops you on Home to navigate yourself is the version people
        // stop tapping. ACTION_VIEW on the app's own scheme, which App.js reads
        // through Linking; setPackage keeps it inside this app.
        val launch = Intent(Intent.ACTION_VIEW, Uri.parse("${DEEP_LINK}")).apply {
            setPackage(context.packageName)
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TOP)
        }
        val flags = PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE
        val pi = PendingIntent.getActivity(context, 0, launch, flags)
        views.setOnClickPendingIntent(R.id.widget_root, pi)

        mgr.updateAppWidget(widgetId, views)
    }
}
`;

