// Resources both home-screen widgets share: the colour palette, the card
// background, and the helpers that build a preview image.
//
// WHY A SHARED FILE. There are two providers now (the running task, and admin
// Live Tracking) and they must look like one app. The colours used to be hex
// literals inlined in withTaskWidget.js, which is also how the dark-mode bug got
// in: the card background was a hardcoded #FFFFFF, so the widget stayed a white
// slab on a dark home screen. Defining them once, as resources with a
// values-night variant, fixes that with no code path and no state to carry.
//
// Both plugins call writeSharedWidgetRes(). Writing the same bytes twice is
// harmless and order-independent, which matters because config plugins have no
// declared ordering and prebuild may run either first.

const fs = require('fs');
const path = require('path');

// One palette, two themes. Android picks per the system setting — there is no
// runtime check and nothing to pass through the state file.
const LIGHT = {
  widget_bg: '#FFFFFFFF',
  widget_text: '#FF0F172A',
  widget_accent: '#FF1E40AF',
  widget_muted: '#FF64748B',
  widget_divider: '#FFE5E9F0',
};
const DARK = {
  widget_bg: '#FF111A2E',
  widget_text: '#FFF1F5F9',
  // Lifted from the light accent: #1E40AF on a dark card fails contrast badly.
  widget_accent: '#FF93C5FD',
  widget_muted: '#FF94A3B8',
  widget_divider: '#FF243043',
};

const colorsXml = (map) => `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by plugins/widgetShared.js -->
<resources>
${Object.entries(map).map(([k, v]) => `    <color name="${k}">${v}</color>`).join('\n')}
</resources>
`;

// The card. References @color/widget_bg rather than a literal so it follows the
// theme; the stroke keeps the card readable where the wallpaper is close to the
// background colour.
const cardBgXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by plugins/widgetShared.js -->
<shape xmlns:android="http://schemas.android.com/apk/res/android"
    android:shape="rectangle">
    <solid android:color="@color/widget_bg" />
    <stroke android:width="1dp" android:color="@color/widget_divider" />
    <corners android:radius="18dp" />
</shape>
`;

/**
 * Rounded-rectangle path data, for the preview vectors below.
 *
 * Vector drawables are used for the previews rather than <shape> layer-lists
 * because a shape has NO INTRINSIC SIZE. android:previewImage is drawn at the
 * drawable's own size, so a sizeless shape can come out as nothing at all — which
 * would land us right back at the blank picker entry this is meant to fix.
 */
function rr(x, y, w, h, r) {
  const rad = Math.min(r, w / 2, h / 2);
  return [
    `M${x + rad},${y}`,
    `h${w - 2 * rad}`,
    `a${rad},${rad} 0 0 1 ${rad},${rad}`,
    `v${h - 2 * rad}`,
    `a${rad},${rad} 0 0 1 ${-rad},${rad}`,
    `h${-(w - 2 * rad)}`,
    `a${rad},${rad} 0 0 1 ${-rad},${-rad}`,
    `v${-(h - 2 * rad)}`,
    `a${rad},${rad} 0 0 1 ${rad},${-rad}`,
    'z',
  ].join(' ');
}

/**
 * Build a preview vector: a card, and `bars` drawn on it.
 *
 * Deliberately a stylised wireframe rather than fake text. At picker size real
 * words are illegible anyway, and inventing a task name in the preview would put
 * a string on somebody's home screen that no translation ever touches.
 *
 * @param {{w:number,h:number}} size      dp, and the vector's viewport
 * @param {Array} bars  { x, y, w, h, r?, color } in viewport units
 */
function previewVector(size, bars) {
  const paths = bars.map((b) => `    <path
        android:pathData="${rr(b.x, b.y, b.w, b.h, b.r == null ? b.h / 2 : b.r)}"
        android:fillColor="${b.color}" />`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by plugins/widgetShared.js -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${size.w}dp"
    android:height="${size.h}dp"
    android:viewportWidth="${size.w}"
    android:viewportHeight="${size.h}">
    <path
        android:pathData="${rr(0.5, 0.5, size.w - 1, size.h - 1, 10)}"
        android:fillColor="@color/widget_bg"
        android:strokeColor="@color/widget_divider"
        android:strokeWidth="1" />
${paths}
</vector>
`;
}

// The accent rule down the left of the task widget, and beside the Live Tracking
// header. Shared because BOTH layouts reference it — left in withTaskWidget.js it
// would be an invisible cross-plugin dependency, and the Live Tracking widget
// would fail to inflate if that plugin were ever removed from app.json.
const accentBarXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by plugins/widgetShared.js -->
<shape xmlns:android="http://schemas.android.com/apk/res/android"
    android:shape="rectangle">
    <solid android:color="@color/widget_accent" />
    <corners android:radius="2dp" />
</shape>
`;

// The "a task is running" dot.
const dotXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by plugins/widgetShared.js -->
<shape xmlns:android="http://schemas.android.com/apk/res/android"
    android:shape="oval">
    <solid android:color="@color/widget_accent" />
</shape>
`;

function write(file, contents) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents, 'utf8');
}

/** Emit the resources both widgets use. Safe to call from either plugin. */
function writeSharedWidgetRes(mainDir) {
  write(path.join(mainDir, 'res', 'values', 'widget_colors.xml'), colorsXml(LIGHT));
  write(path.join(mainDir, 'res', 'values-night', 'widget_colors.xml'), colorsXml(DARK));
  write(path.join(mainDir, 'res', 'drawable', 'widget_card_bg.xml'), cardBgXml);
  write(path.join(mainDir, 'res', 'drawable', 'widget_accent_bar.xml'), accentBarXml);
  write(path.join(mainDir, 'res', 'drawable', 'widget_dot.xml'), dotXml);
}

module.exports = { LIGHT, DARK, rr, previewVector, write, writeSharedWidgetRes };
